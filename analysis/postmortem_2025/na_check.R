suppressMessages({library(dplyr); library(readr); library(tidyr)})
d <- read_csv("C:/dev/brownlow/analysis/submission_comparison/detailed_predictions_vs_actual.csv", show_col_types=FALSE)
rv <- c("espn","byb","betfair","sen","afl","hs","qp","brebbles","mos","anoafl","dropkick","jt","maher","crow","bg1","bg2","bg3","bg4","bg5","wheelo","consensus")
cat("=== NA counts per rival (of 9522 rows) ===\n")
na <- sapply(d[rv], function(x) sum(is.na(x)))
print(na)
cat("\n=== Of NA rows, what is the actual vote distribution? (qp) ===\n")
print(table(d$Actual[is.na(d$qp)]))
cat("\n=== LEADERBOARD RECOMPUTED, NA treated as 0, all 9522 rows ===\n")
rmse <- function(p,a) sqrt(mean((p-a)^2))
lb <- sapply(rv, function(m) rmse(coalesce(d[[m]],0), d$Actual))
lb <- c(lb, our_submission = rmse(d$brownlow_votes, d$Actual))
print(round(sort(lb), 5))
cat("\n=== As-reported (NA rows dropped per model) for contrast ===\n")
lb2 <- sapply(rv, function(m){ i <- !is.na(d[[m]]); rmse(d[[m]][i], d$Actual[i])})
lb2 <- c(lb2, our_submission = rmse(d$brownlow_votes, d$Actual))
print(round(sort(lb2), 5))
cat("\n=== Per-match total votes by model (should be 6) ===\n")
tv <- d %>% group_by(match_id) %>% summarise(across(all_of(c(rv,"brownlow_votes")), ~sum(coalesce(.x,0))))
print(round(sapply(tv[-1], mean), 3))
